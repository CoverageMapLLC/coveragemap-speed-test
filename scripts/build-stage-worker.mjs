#!/usr/bin/env node
// Bundles the browser stage worker (src/browser/stage-worker-entry.ts) into a single classic
// script and writes it to src/browser/stage-worker-source.generated.ts as a string. The
// library starts the worker from a `blob:` URL made from that string, so applications need
// no bundler configuration for it. Runs before build, typecheck, lint, and the tests.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/browser/stage-worker-entry.ts');
const output = join(root, 'src/browser/stage-worker-source.generated.ts');

export async function buildStageWorker() {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    // Node.js-only code paths (worker threads, raw TCP) read import.meta.url; they never run here.
    logOverride: { 'empty-import-meta': 'silent' },
    logLevel: 'warning',
  });
  const source = result.outputFiles[0].text.trim();
  const module =
    '// Generated by scripts/build-stage-worker.mjs from src/browser/stage-worker-entry.ts. Do not edit.\n' +
    `export const STAGE_WORKER_SOURCE: string = ${JSON.stringify(source)};\n`;
  const existing = await readFile(output, 'utf8').catch(() => null);
  if (existing !== module) {
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, module);
  }
  return { bytes: source.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { bytes } = await buildStageWorker();
  console.log(`stage worker: ${(bytes / 1024).toFixed(1)} KB`);
}
